"""Write INDEX.md: every day, grouped by phase, with links to its folder, notes, and tests.

    python3 tools/build_index.py           rewrite INDEX.md
    python3 tools/build_index.py --check   exit 1 if INDEX.md is out of date

The index is generated, not hand-edited, so it can't drift from the
folders; --check is there to catch a day added without regenerating it.
"""

from __future__ import annotations

import argparse
import sys

from daycatalog import PHASES, PROJECTS, REPO, discover

INDEX = REPO / "INDEX.md"


def _link(text: str, target: str) -> str:
    return f"[{text}]({target})"


def render(days) -> str:
    by_number = {d.number: d for d in days}
    runnable = sum(d.runnable for d in days)
    tested = sum(bool(d.tests) for d in days)
    lines = [
        "# Index of every day",
        "",
        "Generated by `python3 tools/build_index.py`; don't edit by hand.",
        "",
        f"{len(days)} days so far: {runnable} have a runnable walkthrough (`main.py`), {tested} have a test suite. "
        "Run any of them from the repo root with `python3 tools/run_day.py NN` (add `--tests` for its suite), "
        "or check them all with `python3 tools/check_all.py`.",
        "",
        "## Projects",
        "",
    ]
    for lo, hi, name, closing in PROJECTS:
        days_in = [by_number[n] for n in range(lo, hi + 1) if n in by_number]
        if not days_in:
            continue
        readme = by_number.get(closing)
        target = readme.rel(readme.path / "README.md") if readme and (readme.path / "README.md").exists() else days_in[0].rel()
        lines.append(f"- **{_link(name, target)}**: Days {lo}–{hi}")
    for lo, hi, name in PHASES:
        in_phase = [d for d in days if lo <= d.number <= hi]
        if not in_phase:
            continue
        lines += ["", f"## {name} (Days {lo}–{hi})", "", "| day | date | topic | run | tests | notes |", "|---:|---|---|:---:|:---:|---|"]
        for d in in_phase:
            notes = ", ".join(_link(n.name, d.rel(n)) for n in d.notes) or "—"
            tests = ", ".join(_link(t.name, d.rel(t)) for t in d.tests) or "—"
            lines.append(
                f"| {d.number} | {d.date or '—'} | {_link(d.title, d.rel())} | {'✓' if d.runnable else '—'} | {tests} | {notes} |"
            )
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if INDEX.md differs from what would be generated")
    args = parser.parse_args(argv)
    text = render(discover())
    if args.check:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current != text:
            print("INDEX.md is out of date; run python3 tools/build_index.py", file=sys.stderr)
            return 1
        print("INDEX.md is up to date")
        return 0
    INDEX.write_text(text, encoding="utf-8")
    print(f"wrote {INDEX.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
