"""Run every day's test suite and write a health report.

    python3 tools/check_all.py                    all days, report to stdout
    python3 tools/check_all.py --days 81-89       a range
    python3 tools/check_all.py --write HEALTH.md  also save the report

Each suite runs in its own process inside its own folder, the same way
`run_day.py NN --tests` runs it, so one day's imports and output files
can't leak into another's.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import time
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

from daycatalog import REPO, discover
from run_day import command_for

RAN = re.compile(r"^Ran (\d+) tests? in", re.M)
SUMMARY = re.compile(r"^(OK|FAILED)(?: \((.*)\))?\s*$", re.M)


@dataclass
class SuiteResult:
    day: int
    title: str
    tests: int | None
    status: str  # "ok", "failed", "error", or "timeout"
    detail: str
    seconds: float


def parse_unittest(stderr: str, returncode: int):
    """(tests run, status, detail) from unittest's closing lines."""
    ran = RAN.findall(stderr)
    tests = int(ran[-1]) if ran else None
    summary = SUMMARY.findall(stderr)
    if summary:
        word, detail = summary[-1]
        # "OK (skipped=2)" still passes; anything FAILED doesn't
        return tests, "ok" if word == "OK" and returncode == 0 else "failed", detail
    # no summary line at all: the suite didn't even import
    last = stderr.strip().splitlines()[-1] if stderr.strip() else f"exit code {returncode}"
    return tests, "error", last


def run_suite(day, timeout: float) -> SuiteResult:
    start = time.monotonic()
    try:
        proc = subprocess.run(command_for(day, tests=True), cwd=day.path, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return SuiteResult(day.number, day.title, None, "timeout", f"over {timeout:g}s", time.monotonic() - start)
    tests, status, detail = parse_unittest(proc.stderr, proc.returncode)
    return SuiteResult(day.number, day.title, tests, status, detail, time.monotonic() - start)


def parse_range(text: str | None):
    """'81-89' or '87' -> (lo, hi); None -> everything."""
    if not text:
        return 0, 10**6
    match = re.fullmatch(r"(\d+)(?:-(\d+))?", text.strip())
    if not match:
        raise ValueError("use a day number or a range like 81-89")
    lo = int(match.group(1))
    hi = int(match.group(2) or lo)
    if hi < lo:
        raise ValueError("range end is before its start")
    return lo, hi


def report(results, untested) -> str:
    passed = [r for r in results if r.status == "ok"]
    total_tests = sum(r.tests or 0 for r in results)
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    headline = f"**{len(passed)} of {len(results)} suites pass**, {total_tests} tests in all."
    if untested:
        headline += f" {len(untested)} days in range have no tests."
    lines = [
        "# Test health",
        "",
        f"Generated by `python3 tools/check_all.py` on {stamp}.",
        "",
        headline,
        "",
        "| day | topic | tests | result | seconds |",
        "|---:|---|---:|---|---:|",
    ]
    for r in results:
        result = "ok" if r.status == "ok" else f"**{r.status}**"
        if r.detail:
            result += f" ({r.detail})"
        lines.append(f"| {r.day} | {r.title} | {r.tests if r.tests is not None else '?'} | {result} | {r.seconds:.1f} |")
    if untested:
        lines += ["", "Days without tests: " + ", ".join(str(d) for d in untested) + "."]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--days", help="a day or a range, e.g. 81-89")
    parser.add_argument("--timeout", type=float, default=600, help="seconds allowed per suite")
    parser.add_argument("--write", help="also save the report here (relative to the repo root)")
    args = parser.parse_args(argv)

    lo, hi = parse_range(args.days)
    days = [d for d in discover() if lo <= d.number <= hi]
    results = []
    for day in (d for d in days if d.tests):
        result = run_suite(day, args.timeout)
        print(f"day {result.day:>3}  {result.status:<7} {result.tests or 0:>3} tests  {result.seconds:5.1f}s", file=sys.stderr, flush=True)
        results.append(result)
    text = report(results, [d.number for d in days if not d.tests])
    print(text)
    if args.write:
        (REPO / args.write).write_text(text, encoding="utf-8")
    # a non-zero exit lets a hook or CI stop on the first broken day
    return 0 if all(r.status == "ok" for r in results) else 1


if __name__ == "__main__":
    sys.exit(main())
